// Keep branch-based Pages entry points in sync with the canonical static site.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,'dist',file),'utf8').replace(/^\uFEFF/,'');
const notice='<!-- Generated by npm run build. Edit the corresponding file in dist/. -->\n';
const home=read('index.html')
  .replace('<html lang="pt-BR">','<html lang="pt-BR" data-asset-base="dist/">')
  .replace(/<(?:script|link)\b[^>]*>/g,tag=>tag.replace(/\b(src|href)="([^"]+)"/g,(_,attribute,url)=>`${attribute}="dist/${url}"`));
const help=read('help/index.html')
  .replaceAll('../assets/','../dist/assets/')
  .replace('href="../styles.css','href="../dist/styles.css')
  .replace('href="../favicon.svg','href="../dist/favicon.svg')
  .replace('href="help.css','href="../dist/help/help.css');
fs.mkdirSync(path.join(root,'help'),{recursive:true});
fs.writeFileSync(path.join(root,'index.html'),notice+home);
fs.writeFileSync(path.join(root,'help/index.html'),notice+help);
fs.writeFileSync(path.join(root,'.nojekyll'),'');
console.log('Home and /help entry points are ready. Static runtime: dist/.');
